-- =====================================================
-- TABLA: crm_pipelines
-- Pipelines de ventas personalizables
-- =====================================================
CREATE TABLE public.crm_pipelines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID REFERENCES auth.users NOT NULL,
    name TEXT NOT NULL,
    description TEXT,
    is_default BOOLEAN DEFAULT FALSE,
    currency TEXT DEFAULT 'EUR',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);
-- =====================================================
-- TABLA: crm_stages
-- Etapas dentro de cada pipeline (columnas del Kanban)
-- =====================================================
CREATE TABLE public.crm_stages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pipeline_id BIGINT REFERENCES public.crm_pipelines ON DELETE CASCADE NOT NULL,
    name TEXT NOT NULL,
    color TEXT DEFAULT 'indigo',
    position INTEGER NOT NULL DEFAULT 0,
    probability INTEGER DEFAULT 10,
    -- Probabilidad de cierre (0-100)
    is_won BOOLEAN DEFAULT FALSE,
    -- Etapa de éxito
    is_lost BOOLEAN DEFAULT FALSE,
    -- Etapa de pérdida
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);
-- =====================================================
-- TABLA: crm_companies
-- Empresas/Cuentas
-- =====================================================
CREATE TABLE public.crm_companies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID REFERENCES auth.users NOT NULL,
    -- Información básica
    name TEXT NOT NULL,
    legal_name TEXT,
    tax_id TEXT,
    -- NIF/CIF/VAT
    -- Contacto
    email TEXT,
    phone TEXT,
    website TEXT,
    -- Dirección
    address_street TEXT,
    address_city TEXT,
    address_state TEXT,
    address_zip TEXT,
    address_country TEXT DEFAULT 'España',
    -- Clasificación
    industry TEXT,
    -- Sector/Industria
    company_size TEXT,
    -- 1-10, 11-50, 51-200, 201-500, 500+
    annual_revenue DECIMAL(15, 2),
    -- Ingresos anuales estimados
    -- Redes sociales
    linkedin_url TEXT,
    twitter_url TEXT,
    -- Metadata
    source TEXT,
    -- Fuente de adquisición
    notes TEXT,
    logo_url TEXT,
    -- Estado
    is_customer BOOLEAN DEFAULT FALSE,
    is_supplier BOOLEAN DEFAULT FALSE,
    is_active BOOLEAN DEFAULT TRUE,
    -- Timestamps
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);
-- =====================================================
-- TABLA: crm_contacts
