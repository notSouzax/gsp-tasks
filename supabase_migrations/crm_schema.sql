-- TABLA: crm_products
-- Productos/Servicios para cotizaciones
-- =====================================================
CREATE TABLE public.crm_products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID REFERENCES auth.users NOT NULL,
    name TEXT NOT NULL,
    description TEXT,
    sku TEXT,
    -- Código de producto
    -- Precios
    unit_price DECIMAL(15, 2) DEFAULT 0,
    cost_price DECIMAL(15, 2) DEFAULT 0,
    -- Categorización
    category TEXT,
    -- Estado
    is_active BOOLEAN DEFAULT TRUE,
    -- Timestamps
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);
-- =====================================================
-- TABLA: crm_opportunity_products
-- Productos asociados a oportunidades (líneas de cotización)
-- =====================================================
CREATE TABLE public.crm_opportunity_products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    opportunity_id BIGINT REFERENCES public.crm_opportunities ON DELETE CASCADE NOT NULL,
    product_id BIGINT REFERENCES public.crm_products ON DELETE
    SET NULL,
        -- Puede ser producto personalizado (sin product_id)
        product_name TEXT NOT NULL,
        description TEXT,
        -- Cantidades y precios
        quantity DECIMAL(10, 2) DEFAULT 1,
        unit_price DECIMAL(15, 2) DEFAULT 0,
        discount_percent DECIMAL(5, 2) DEFAULT 0,
        tax_percent DECIMAL(5, 2) DEFAULT 21,
        -- IVA por defecto 21%
        -- Totales calculados
        subtotal DECIMAL(15, 2) GENERATED ALWAYS AS (
            quantity * unit_price * (1 - discount_percent / 100)
        ) STORED,
        total DECIMAL(15, 2) GENERATED ALWAYS AS (
            quantity * unit_price * (1 - discount_percent / 100) * (1 + tax_percent / 100)
        ) STORED,
        -- Posición en la lista
        position INTEGER DEFAULT 0,
        created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);
