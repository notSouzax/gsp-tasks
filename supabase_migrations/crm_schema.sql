-- =====================================================
-- TABLA: crm_opportunities
-- Oportunidades de venta
-- =====================================================
CREATE TABLE public.crm_opportunities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID REFERENCES auth.users NOT NULL,
    pipeline_id BIGINT REFERENCES public.crm_pipelines ON DELETE CASCADE NOT NULL,
    stage_id BIGINT REFERENCES public.crm_stages ON DELETE
    SET NULL,
        contact_id BIGINT REFERENCES public.crm_contacts ON DELETE
    SET NULL,
        company_id BIGINT REFERENCES public.crm_companies ON DELETE
    SET NULL,
        -- Información de la oportunidad
        name TEXT NOT NULL,
        description TEXT,
        -- Valores económicos
        expected_revenue DECIMAL(15, 2) DEFAULT 0,
        -- Valor esperado
        probability INTEGER DEFAULT 10,
        -- Probabilidad de cierre (0-100)
        weighted_revenue DECIMAL(15, 2) GENERATED ALWAYS AS (expected_revenue * probability / 100) STORED,
        -- Fechas
        expected_close_date DATE,
        actual_close_date DATE,
        -- Clasificación
        priority TEXT DEFAULT 'medium',
        -- low, medium, high, urgent
        source TEXT,
        -- Fuente de la oportunidad
        -- Estado
        is_won BOOLEAN DEFAULT FALSE,
        is_lost BOOLEAN DEFAULT FALSE,
        lost_reason TEXT,
        -- Posición en el Kanban
        position INTEGER DEFAULT 0,
        -- Metadata
        notes TEXT,
        -- Timestamps
        created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
        updated_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);
-- =====================================================
-- TABLA: crm_activities
-- Actividades programadas (llamadas, reuniones, tareas)
-- =====================================================
CREATE TABLE public.crm_activities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID REFERENCES auth.users NOT NULL,
    -- Relaciones (al menos una debe estar presente)
    contact_id BIGINT REFERENCES public.crm_contacts ON DELETE CASCADE,
    company_id BIGINT REFERENCES public.crm_companies ON DELETE CASCADE,
    opportunity_id BIGINT REFERENCES public.crm_opportunities ON DELETE CASCADE,
    -- Tipo de actividad
    activity_type TEXT NOT NULL DEFAULT 'task',
    -- call, meeting, email, task, note, deadline
    -- Información
    title TEXT NOT NULL,
    description TEXT,
    -- Programación
    due_date TIMESTAMP WITH TIME ZONE,
    duration_minutes INTEGER DEFAULT 30,
    -- Estado
    is_done BOOLEAN DEFAULT FALSE,
    completed_at TIMESTAMP WITH TIME ZONE,
    -- Prioridad
    priority TEXT DEFAULT 'normal',
    -- low, normal, high, urgent
    -- Resultado (para llamadas/reuniones)
    outcome TEXT,
    -- successful, no_answer, left_message, rescheduled
    outcome_notes TEXT,
    -- Timestamps
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);
