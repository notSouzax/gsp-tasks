-- FUNCIÓN: Crear pipeline por defecto para nuevos usuarios
-- =====================================================
CREATE OR REPLACE FUNCTION public.create_default_crm_pipeline() RETURNS TRIGGER AS $$
DECLARE new_pipeline_id BIGINT;
BEGIN -- Crear pipeline por defecto
INSERT INTO public.crm_pipelines (user_id, name, description, is_default)
VALUES (
        NEW.id,
        'Pipeline Principal',
        'Pipeline de ventas predeterminado',
        TRUE
    )
RETURNING id INTO new_pipeline_id;
-- Crear etapas por defecto
INSERT INTO public.crm_stages (
        pipeline_id,
        name,
        color,
        position,
        probability,
        is_won,
        is_lost
    )
VALUES (
        new_pipeline_id,
        'Nuevo',
        'slate',
        0,
        10,
        FALSE,
        FALSE
    ),
    (
        new_pipeline_id,
        'Calificado',
        'blue',
        1,
        20,
        FALSE,
        FALSE
    ),
    (
        new_pipeline_id,
        'Propuesta',
        'purple',
        2,
        40,
        FALSE,
        FALSE
    ),
    (
        new_pipeline_id,
        'Negociación',
        'amber',
        3,
        60,
        FALSE,
        FALSE
    ),
    (
        new_pipeline_id,
        'Ganado',
        'emerald',
        4,
        100,
        TRUE,
        FALSE
    ),
    (
        new_pipeline_id,
        'Perdido',
        'red',
        5,
        0,
        FALSE,
        TRUE
    );
RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;
-- Trigger para crear pipeline cuando se crea un usuario
CREATE TRIGGER on_crm_user_created
AFTER
INSERT ON public.profiles FOR EACH ROW EXECUTE PROCEDURE public.create_default_crm_pipeline();
